#!/usr/bin/env python3
"""course_path.py: keep the learner's path through the course in one place.

The path (the order of the day, what each step is for, what it needs first,
when it is done, what comes next) lives in ``task1/lab/task/part1/course_path.json``.
This script projects that file into the notebooks:

- a **path header** markdown cell right after the title cell of every notebook
  on the path (part of the day, minutes, Home link, what you need first,
  previous and next links);
- a **card** (markdown, role ``handoff``) right after the notebook's own ``## Next`` cell
  (before the closing image when there is none): when the step is done, the
  pauses that follow, the next step with its link, and the assessment after
  that with what it grades; on the last step, a reminder to click ASSESS TASK
  that names the assessments on the path, before the pauses;
- the **map** cell on ``00_Home.ipynb``;
- a ``milestone`` tag on the one code cell per notebook that shows the lesson
  was applied. course_ui.py counts a step as done once that cell has run
  without an error in the saved notebook (the tag itself changes nothing).

A step with ``course_docs`` instead of ``path`` is a page of the Course Docs
site (``course_docs`` is its source under ``docs/``, and its H1 is the step's
title). It has no notebook, so it gets no header, card or milestone; wherever
another cell names it, the text tells learners to open Course Docs from the
JupyterLab Launcher. ``--check`` also fails when that page is missing or has
another title.

Generated cells are found by ``metadata.course_path`` (``header``,
``handoff``, ``home-map``), never by position, so re-running after content
edits is safe; a generated cell that drifted out of place is moved back.
A generated header or card left over from an older layout (another step's
id, for example after two notebooks were merged) is removed and regenerated,
and a ``milestone`` tag on a cell that is no longer the step's milestone is
taken off. Content cells keep their ids; generated cells have ids of the form
``path-header-<step>`` and ``path-handoff-<step>``. Notebooks are written back
the way JupyterLab saves them (indent 1, UTF-8, trailing newline), so an
unchanged notebook is byte-identical.

    python3 -I task1/scripts/course_path.py --apply     # rewrite the notebooks
    python3 -I task1/scripts/course_path.py --check     # CI: exit 1 if any notebook is out of date

``course_ui.py`` reads the same JSON at run time for the course bar and the
Home page card.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import posixpath
import re
import sys

HERE = pathlib.Path(__file__).resolve()
TASK_DIR = HERE.parents[1] / "lab" / "task"
PATH_FILE = TASK_DIR / "part1" / "course_path.json"
HOME = TASK_DIR / "00_Home.ipynb"
DOCS_DIR = HERE.parents[2] / "docs"                      # the Course Docs site source
COURSE_DOCS_HINT = "(open Course Docs from the JupyterLab Launcher)"
HEADER_IMG = "images/nvidia_header.png"
STEP_KINDS = ("notebook", "terminal", "assessment")      # steps that count as "step k of n"
PAUSE_KINDS = ("slides", "break", "lunch")
KINDS = STEP_KINDS + PAUSE_KINDS
MARK = "<!-- generated by task1/scripts/course_path.py from part1/course_path.json; edit the JSON, not this cell -->"
NEXT_CELL = re.compile(r"^## Next\b")
GENERATED_ROLES = ("header", "handoff")


# --------------------------------------------------------------------------- notebook io

def read_nb(path: pathlib.Path):
    text = path.read_text(encoding="utf-8")
    return json.loads(text), text


def dump_nb(nb, like: str) -> str:
    """Serialize the way the original was serialized (JupyterLab: indent 1, non-ASCII kept)."""
    out = json.dumps(nb, indent=1, ensure_ascii=like.isascii())
    if like.endswith("\n"):
        out += "\n"
    return out


def write_nb(path: pathlib.Path, nb, like: str) -> bool:
    new = dump_nb(nb, like)
    if new == like:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def md_cell(cell_id: str, text: str, role: str) -> dict:
    return {"cell_type": "markdown", "id": cell_id, "metadata": {"course_path": role},
            "source": _as_source(text)}


def _as_source(text: str):
    lines = text.split("\n")
    return [line + "\n" for line in lines[:-1]] + ([lines[-1]] if lines[-1] else [])


def _text(cell) -> str:
    return "".join(cell.get("source", []))


# --------------------------------------------------------------------------- the path

def load_path(path_file: pathlib.Path = PATH_FILE) -> dict:
    data = json.loads(path_file.read_text(encoding="utf-8"))
    steps = data["steps"]
    counted = [s for s in steps if s.get("kind", "notebook") in STEP_KINDS]
    for k, s in enumerate(counted, 1):
        s["_k"], s["_n"] = k, len(counted)
    for i, s in enumerate(steps):
        s["_index"] = i
    return data


def rel(target: str, here_dir: str) -> str:
    """Link to ``target`` (relative to the lab root) from a notebook in ``here_dir`` (relative to the lab root)."""
    return posixpath.relpath(target, here_dir or ".")


def _link(step: dict, here_dir: str) -> str:
    """A link to the step's notebook; for a Course Docs page, where to open it; otherwise the bare title."""
    if step.get("path"):
        return f"[{step['title']}]({rel(step['path'], here_dir)})"
    if step.get("course_docs"):
        return f"{step['title']} {COURSE_DOCS_HINT}"
    return step["title"]


def _mins(step: dict) -> str:
    m = step.get("minutes")
    return f"about {m} min" if m else ""


def _summary(step: dict) -> str:
    """The one line about a step ('question' is the field's name in older copies of the JSON)."""
    return step.get("summary") or step.get("question") or ""


def _join(items) -> str:
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def _cell(text: str) -> str:
    """Text for a Markdown table cell."""
    return str(text).replace("|", "\\|")


def previous_step(steps, index):
    for s in reversed(steps[:index]):
        if s.get("kind", "notebook") in STEP_KINDS:
            return s
    return None


def following(steps, index):
    """(pauses between, next counted step, the counted step after that) for the step at ``index``."""
    pauses, nxt, after = [], None, None
    for s in steps[index + 1:]:
        kind = s.get("kind", "notebook")
        if nxt is None:
            if kind in PAUSE_KINDS:
                pauses.append(s)
            elif kind in STEP_KINDS:
                nxt = s
        elif kind in STEP_KINDS:
            after = s
            break
    return pauses, nxt, after


def _pause_head(p: dict) -> str:
    return f"{p['title']}, {p['minutes']} min" if p.get("minutes") else p["title"]


def _pause_phrase(pauses) -> str:
    return ", then ".join(_pause_head(p) for p in pauses)


def pause_lines(pauses) -> list:
    """'Then: Break, 10 min.' on one line; one line per pause when a pause says what to do in it."""
    if not pauses:
        return []
    if not any(p.get("summary") for p in pauses):
        return [">", f"> **Then:** {_pause_phrase(pauses)}."]
    lines = [">", "> **Then:**", ">"]
    for p in pauses:
        lines.append(f"> - {_pause_head(p)}." + (f" {p['summary']}" if p.get("summary") else ""))
    return lines


def assess_task_reminder(step: dict, data: dict, here_dir: str) -> str:
    """The last step's reminder to click ASSESS TASK, naming the assessments on the path.

    It follows "This is the last step on this launch." and comes before the pauses, so a learner who
    reads the card from the top clicks ASSESS TASK before pressing the next launch button. Empty when
    the path has no assessment, or when this step's own done_when already says it.
    """
    if "ASSESS TASK" in "; ".join(step.get("done_when", [])):
        return ""
    names = [_link(s, here_dir) for s in data["steps"] if s.get("kind") == "assessment"]
    if not names:
        return ""
    cells = "cell" if len(names) == 1 else "cells"
    return (" Before you leave, click ASSESS TASK on the course page if you have not done so yet. "
            f"The Submit {cells} in {_join(names)} must show PASSED first.")


def header_text(step: dict, data: dict) -> str:
    """The strip under the title: where this notebook sits, what you need first, the neighbours.

    The notebook's own title cell says what it is for, so the strip does not repeat it.
    """
    here_dir = str(pathlib.PurePosixPath(step["path"]).parent)
    steps = data["steps"]
    prev = previous_step(steps, step["_index"])
    _, nxt, _ = following(steps, step["_index"])
    # No "Step k of n": the titles carry their own numbers (1. Inspect VSS Deployment is the second step).
    first = " &middot; ".join(p for p in (f"**{step['block']}**" if step.get("block") else "",
                                          _mins(step) if step.get("minutes") else "") if p)
    first += f" &nbsp;|&nbsp; [Home]({rel('00_Home.ipynb', here_dir)})"
    lines = [MARK, f"> {first}"]
    if step.get("needs_before"):
        lines += [">", "> **Before you start:** " + "; ".join(step["needs_before"]) + "."]
    nav = []
    if prev:
        nav.append("Previous: " + _link(prev, here_dir))
    if nxt:
        nav.append("Next: " + _link(nxt, here_dir))
    if nav:
        lines += [">", "> " + " &middot; ".join(nav)]
    return "\n".join(lines) + "\n"


def handoff_text(step: dict, data: dict) -> str:
    """The card after the notebook's own Next cell: when you are done, the pauses, the next step, the assessment after."""
    here_dir = str(pathlib.PurePosixPath(step["path"]).parent)
    steps = data["steps"]
    pauses, nxt, after = following(steps, step["_index"])
    lines = [MARK]
    if step.get("done_when"):
        lines += ["> **You are done with this step when:** " + "; ".join(step["done_when"]) + "."]
    elif step.get("leaves_with"):
        lines += ["> **Take with you:** " + "; ".join(step["leaves_with"]) + "."]
    if nxt is None:
        # ASSESS TASK first: the pauses after the last step tell the learner to press the next launch button.
        lines += [">", "> **This is the last step on this launch.**" + assess_task_reminder(step, data, here_dir)]
        lines += pause_lines(pauses)
    else:
        lines += pause_lines(pauses)
        line = f"> **Next: {_link(nxt, here_dir)}**"
        extra = " &middot; ".join(x for x in (nxt.get("block"), _mins(nxt)) if x)
        if extra:
            line += f" &middot; {extra}"
        if _summary(nxt):
            line += f"  \n> {_summary(nxt)}"
        lines += [">", line]
        if after and after.get("kind") == "assessment":
            gloss = after.get("grades")
            lines += [">", f"> After that: **{_link(after, here_dir)}** ({_mins(after)})." + (f" {gloss}" if gloss else "")]
    lines += [">", f"> [Back to Home]({rel('00_Home.ipynb', here_dir)})"]
    return "\n".join(lines) + "\n"


def home_map_text(data: dict) -> str:
    """The day as a table, then the minutes per part of the day (breaks and lunch included)."""
    rows = ["| Step | Part | Min | What you do |", "|---|---|---|---|"]
    parts = {}
    for s in data["steps"]:
        counted = s.get("kind", "notebook") in STEP_KINDS
        title = _link(s, ".") if counted else s["title"]
        rows.append(f"| {_cell(title)} | {_cell(s.get('block', ''))} | {s.get('minutes', '')} | {_cell(_summary(s))} |")
        part = s.get("block") or s["title"]
        parts[part] = parts.get(part, 0) + int(s.get("minutes") or 0)
    day = ", ".join(f"{name} {minutes} min" for name, minutes in parts.items())
    total = sum(parts.values())
    return (MARK + "\n" + "\n".join(rows) + f"\n\nThe day: {day} ({total} min in all). "
            "Links open in a new JupyterLab tab; this page stays open.\n")


# --------------------------------------------------------------------------- applying

def find_role(cells, role):
    for i, c in enumerate(cells):
        if c.get("metadata", {}).get("course_path") == role:
            return i
    return None


def header_index(cells) -> int:
    """Right after the title cell ('# N. Title'), which the house-pattern test keeps at cells[1]."""
    for i, c in enumerate(cells[:4]):
        if c["cell_type"] == "markdown" and _text(c).lstrip().startswith("# ") and c.get("metadata", {}).get("course_path") is None:
            return i + 1
    return 1


def handoff_index(cells) -> int:
    """Right after the last '## Next' cell; before the closing image when there is none."""
    last = None
    for i, c in enumerate(cells):
        if c["cell_type"] == "markdown" and c.get("metadata", {}).get("course_path") is None and NEXT_CELL.match(_text(c).lstrip()):
            last = i
    return last + 1 if last is not None else len(cells) - 1


def drop_stale(cells, step: dict) -> None:
    """Take out what an older layout left behind in this notebook.

    A generated header or card whose id belongs to another step (two notebooks merged into one, a
    renamed step) is removed so it can be regenerated under this step's id, and a milestone tag on a cell
    that is no longer this step's milestone is taken off.
    """
    sid, mid = step["id"], step.get("milestone_cell_id")
    own = {f"path-{role}-{sid}" for role in GENERATED_ROLES}
    cells[:] = [c for c in cells
                if c.get("metadata", {}).get("course_path") not in GENERATED_ROLES or c.get("id") in own]
    for c in cells:
        meta = c.get("metadata", {})
        if c.get("id") == mid or ("course_path_milestone" not in meta and "milestone" not in meta.get("tags", [])):
            continue
        meta.pop("course_path_milestone", None)
        if "tags" in meta:
            meta["tags"] = [t for t in meta["tags"] if t != "milestone"]
            if not meta["tags"]:
                del meta["tags"]


def place(cells, role, cell_id, text, where) -> None:
    """Ensure one cell with this role exists, with this text, at the index ``where(cells_without_it)`` gives."""
    i = find_role(cells, role)
    cell = cells.pop(i) if i is not None else md_cell(cell_id, text, role)
    cell["source"] = _as_source(text)
    cells.insert(where(cells), cell)


def apply_step(step: dict, data: dict):
    """Project one step into its notebook. Returns (changed, problems, payload_or_None)."""
    path = TASK_DIR / step["path"]
    if not path.is_file():
        return False, [f"{step['path']}: notebook missing"], None
    problems = []
    nb, raw = read_nb(path)
    cells = nb["cells"]
    if not (cells and HEADER_IMG in _text(cells[0]) and HEADER_IMG in _text(cells[-1])):
        problems.append(f"{step['path']}: expected the header image as first and last cell")
    sid = step["id"]
    drop_stale(cells, step)
    place(cells, "header", f"path-header-{sid}", header_text(step, data), header_index)
    place(cells, "handoff", f"path-handoff-{sid}", handoff_text(step, data), handoff_index)

    mid = step.get("milestone_cell_id")
    if mid:
        hits = [c for c in cells if c.get("id") == mid]
        if not hits:
            problems.append(f"{step['path']}: milestone cell {mid!r} not found")
        else:
            meta = hits[0].setdefault("metadata", {})
            tags = meta.setdefault("tags", [])
            if "milestone" not in tags:
                tags.append("milestone")
            meta["course_path_milestone"] = sid

    ids = [c.get("id") for c in cells]
    if len(ids) != len(set(ids)):
        problems.append(f"{step['path']}: duplicate cell ids after projection")
    return dump_nb(nb, raw) != raw, problems, (path, nb, raw)


def apply_home(data: dict):
    nb, raw = read_nb(HOME)
    cells = nb["cells"]
    i = find_role(cells, "home-map")
    if i is None:
        return False, [f"{HOME.name}: no cell with metadata course_path = home-map"], None
    cells[i]["source"] = _as_source(home_map_text(data))
    return dump_nb(nb, raw) != raw, [], (HOME, nb, raw)


def path_problems(data: dict) -> list:
    """Mistakes in the JSON itself: repeated ids, unknown kinds, a counted step that is neither a notebook with a
    milestone nor a Course Docs page, a step that claims to be both."""
    problems, seen = [], set()
    for s in data["steps"]:
        sid = s.get("id")
        if sid in seen:
            problems.append(f"course_path.json: step id {sid!r} is used twice")
        seen.add(sid)
        kind = s.get("kind", "notebook")
        if kind not in KINDS:
            problems.append(f"course_path.json: step {sid!r} has unknown kind {kind!r}")
        elif s.get("course_docs") and (s.get("path") or s.get("milestone_cell_id")):
            problems.append(f"course_path.json: step {sid!r} names a Course Docs page and also a notebook path "
                            "or milestone_cell_id")
        elif kind in STEP_KINDS and not s.get("course_docs") and not (s.get("path") and s.get("milestone_cell_id")):
            problems.append(f"course_path.json: step {sid!r} counts as a step but has no path or no milestone_cell_id, "
                            "and no course_docs page")
    return problems


def page_title(text: str) -> str | None:
    """The H1 of a Markdown page: its first '# ' line outside fenced blocks."""
    fenced = False
    for line in text.splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
        elif not fenced and line.startswith("# "):
            return line[2:].strip()
    return None


def course_docs_problems(data: dict, docs_dir: pathlib.Path = DOCS_DIR) -> list:
    """Each Course Docs step's page exists under docs/ and opens with the step's title, the name the cards use."""
    problems = []
    for s in data["steps"]:
        page = s.get("course_docs")
        if not page:
            continue
        path = docs_dir / page
        if not path.is_file():
            problems.append(f"docs/{page}: the Course Docs page of step {s['id']!r} is missing")
            continue
        title = page_title(path.read_text(encoding="utf-8"))
        if title != s["title"]:
            problems.append(f"docs/{page}: its H1 is {title!r}, but step {s['id']!r} calls it {s['title']!r}")
    return problems


def run(apply: bool) -> int:
    data = load_path()
    docs_problems = course_docs_problems(data)
    problems, pending, stale = path_problems(data) + docs_problems, [], []
    for step in data["steps"]:
        if not step.get("path"):
            continue
        changed, probs, payload = apply_step(step, data)
        problems += probs
        if changed and payload:
            stale.append(step["path"])
            pending.append(payload)
    changed, probs, payload = apply_home(data)
    problems += probs
    if changed and payload:
        stale.append("00_Home.ipynb")
        pending.append(payload)
    for p in problems:
        print("PROBLEM:", p)
    if apply:
        for path, nb, raw in pending:
            write_nb(path, nb, raw)
            print("updated", path.relative_to(TASK_DIR))
        if not pending:
            print("every notebook already matches course_path.json")
        return 1 if problems else 0
    if stale:
        print("out of date (run with --apply):")
        for s in stale:
            print("  ", s)
    else:
        pages = [f"docs/{s['course_docs']}" for s in data["steps"] if s.get("course_docs")]
        found = ""
        if pages and not docs_problems:
            found = (f"; the Course Docs page {pages[0]} carries its step's title" if len(pages) == 1 else
                     f"; the Course Docs pages {_join(pages)} carry their steps' titles")
        print(f"course path: {len([s for s in data['steps'] if s.get('path')])} notebooks match course_path.json{found}")
    return 1 if (stale or problems) else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true", help="rewrite notebooks from course_path.json")
    mode.add_argument("--check", action="store_true", help="exit 1 if any notebook is out of date")
    args = ap.parse_args(argv)
    return run(apply=args.apply)


if __name__ == "__main__":
    sys.exit(main())
